package com.rte_france.antares.datamanager_back.validation;

import com.rte_france.antares.datamanager_back.annotation.CheckStudyGenerationInProgress;
import com.rte_france.antares.datamanager_back.exception.AntaresErrorCode;
import com.rte_france.antares.datamanager_back.exception.BusinessException;
import com.rte_france.antares.datamanager_back.repository.StudyRepository;
import com.rte_france.antares.datamanager_back.repository.model.StudyEntity;
import com.rte_france.antares.datamanager_back.repository.model.StudyStatus;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import org.aspectj.lang.JoinPoint;
import org.aspectj.lang.annotation.Aspect;
import org.aspectj.lang.annotation.Before;
import org.springframework.http.HttpStatus;
import org.springframework.stereotype.Component;
import org.springframework.web.bind.annotation.PathVariable;
import org.springframework.web.bind.annotation.RequestParam;

import java.lang.reflect.Method;
import java.lang.reflect.Parameter;
import java.util.Arrays;
import java.util.Collections;
import java.util.List;

@Aspect
@Component
@RequiredArgsConstructor
@Slf4j
public class StudyGenerationCheckAspect {

    private final StudyRepository studyRepository;

    @Before("@annotation(com.rte_france.antares.datamanager_back.annotation.CheckStudyGenerationInProgress)")
    public void checkStudyGenerationInProgress(JoinPoint joinPoint) {
        Method method = getMethod(joinPoint);
        if (method == null) {
            log.warn("Could not find method for study generation check");
            return;
        }

        CheckStudyGenerationInProgress annotation = method.getAnnotation(CheckStudyGenerationInProgress.class);
        Integer studyId = extractStudyId(joinPoint, method, annotation.value());
        
        if (studyId == null) {
            log.warn("Could not extract studyId from method {}", method.getName());
            return;
        }

        studyRepository.findById(studyId).ifPresent(study -> {
            if (study.getStatus() == StudyStatus.GENERATION_INPROGRESS) {
                String generatingUser = study.getGenerationStartedBy() != null ? study.getGenerationStartedBy() : "unknown";
                throw BusinessException.builder()
                    .antaresErrorCode(AntaresErrorCode.STUDY_GENERATION_IN_PROGRESS)
                    .message("Study {0} is being generated by {1}")
                    .errorMessageArguments(Arrays.asList(study.getName(), generatingUser))
                    .httpStatus(HttpStatus.CONFLICT)
                    .build();
            } else if (study.getStatus() == StudyStatus.GENERATED) {
                throw BusinessException.builder()
                    .antaresErrorCode(AntaresErrorCode.STUDY_ALREADY_GENERATED)
                    .message("Study {0} is already generated")
                    .errorMessageArguments(Collections.singletonList(study.getName()))
                    .httpStatus(HttpStatus.CONFLICT)
                    .build();
            }
        });
    }

    private Integer extractStudyId(JoinPoint joinPoint, Method method, String[] paramNames) {
        Parameter[] parameters = method.getParameters();
        Object[] args = joinPoint.getArgs();
        List<String> names = Arrays.asList(paramNames);

        for (int i = 0; i < parameters.length; i++) {
            Parameter parameter = parameters[i];

            RequestParam requestParam = parameter.getAnnotation(RequestParam.class);
            if (requestParam != null && names.contains(getAnnotationParamName(requestParam.value(), requestParam.name(), parameter.getName()))) {
                Integer value = getIntegerValue(args[i]);
                if (value != null) {
                    return value;
                }
            }

            PathVariable pathVariable = parameter.getAnnotation(PathVariable.class);
            if (pathVariable != null && names.contains(getAnnotationParamName(pathVariable.value(), pathVariable.name(), parameter.getName()))) {
                Integer value = getIntegerValue(args[i]);
                if (value != null) {
                    return value;
                }
            }
        }
        return null;
    }

    private String getAnnotationParamName(String value, String name, String parameterName) {
        if (!value.isEmpty()) {
            return value;
        }
        return !name.isEmpty() ? name : parameterName;
    }

    private Integer getIntegerValue(Object arg) {
        if (arg instanceof Integer) {
            return (Integer) arg;
        }
        return null;
    }

    private Method getMethod(JoinPoint joinPoint) {
        try {
            String methodName = joinPoint.getSignature().getName();
            Class<?> targetClass = joinPoint.getTarget().getClass();
            
            for (Method method : targetClass.getDeclaredMethods()) {
                if (method.getName().equals(methodName)) {
                    return method;
                }
            }
        } catch (Exception e) {
            log.debug("Could not find method for study generation check", e);
        }
        return null;
    }
}

